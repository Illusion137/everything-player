val surroundAudioCodes: Set<String> = setOf("m", "M", "mac3", "MAC3", "meac3", "MEAC3", "i", "I")

fun buildAudioCapability(
  format: SabrFormat,
  isSurroundSupported: Boolean = true,
): AudioFormatCapability? {
  val codecCode = format.codecCode
  if (codecCode.isNullOrEmpty() || codecCode == "f") return null
  if (!isSurroundSupported && surroundAudioCodes.contains(codecCode)) return null

  val capability = AudioFormatCapability.newBuilder()
  AUDIO_CODECS[codecCode]?.let { capability.setAudioCodec(it) }
  SPATIAL_AUDIO_CODECS[codecCode]?.let { capability.setSpatialCapabilityBitmask(it) }
  format.numChannels?.let { capability.setNumChannels(it) }
  return capability.build()
}

fun buildVideoCapability(format: SabrFormat): VideoFormatCapability? {
  val codecCode = format.codecCode
  if (codecCode.isNullOrEmpty() || codecCode == "f") return null

  val capability = VideoFormatCapability.newBuilder()
  VIDEO_CODECS[codecCode]?.let { capability.setVideoCodec(it) }
  capability.setMaxWidth(format.width ?: 0)
  capability.setMaxHeight(format.height ?: 0)
  capability.setMaxFramerate(format.fps ?: 0)
  capability.setIs10BitSupported(format.isHdr)
  capability.setMaxBitrateBps(format.bitrate)
  capability.setEfficient(true)
  return capability.build()
}

fun buildMediaCapabilities(
  videoFormat: SabrFormat? = null,
  audioFormat: SabrFormat? = null,
  isSurroundSupported: Boolean = true,
): MediaCapabilities? {
  val video = videoFormat?.let { buildVideoCapability(it) }
  val audio = audioFormat?.let { buildAudioCapability(it, isSurroundSupported) }

  if (video == null && audio == null) return null

  val capabilities = MediaCapabilities.newBuilder()
  video?.let { capabilities.addVideoFormatCapabilities(it) }
  audio?.let { capabilities.addAudioFormatCapabilities(it) }
  capabilities.setHdrModeBitmask(3)
  return capabilities.build()
}
